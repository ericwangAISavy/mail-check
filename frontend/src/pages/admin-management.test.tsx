import {afterEach,expect,it,vi} from "vitest"
import {cleanup,fireEvent,render,screen,waitFor} from "@testing-library/react"
import {QueryClient,QueryClientProvider} from "@tanstack/react-query"
import {api,request} from "@/lib/api"
import AdminManagement from "./admin-management"
const state=vi.hoisted(()=>({owner:true}))
vi.mock("@/components/auth",()=>({useAuth:()=>({role:"admin",session:{is_owner:state.owner,workspace_id:"legacy"}})}))
vi.mock("@/lib/api",()=>({request:vi.fn(),api:{post:vi.fn()},setWorkspaceIdentity:vi.fn(),getWorkspaceIdentity:vi.fn()}))
const clients:QueryClient[]=[]
afterEach(()=>{cleanup();clients.splice(0).forEach(c=>c.clear());vi.resetAllMocks();vi.restoreAllMocks();state.owner=true})
function mount(jobLinksAccess=false){
  vi.mocked(request).mockImplementation(async url=>url==="/api/admin/backups"?{enabled:true,retain:7,folder:"/backups",running:false,last_error:null,last_success:null,next_due:null,archives:[]} as never:url==="/api/admin/users"?{max_workspaces:4,admins:[{id:1,username:"owner",owner:1,enabled:1,job_links_access:true,workspace_id:"legacy",workspace_name:"Original workspace",health:"running",online:true},{id:2,username:"alice",owner:0,enabled:1,job_links_access:jobLinksAccess,workspace_id:"alice",workspace_name:"Alice workspace",health:"running",online:false}]} as never:{events:[]} as never)
  const client=new QueryClient({defaultOptions:{queries:{retry:false},mutations:{retry:false}}});clients.push(client)
  render(<QueryClientProvider client={client}><AdminManagement/></QueryClientProvider>)
}
it('shows one workspace detail and loads backup or audit data only when opened',async()=>{
 mount();await screen.findByRole('button',{name:'Manage Alice workspace'})
 expect(screen.queryByRole('button',{name:'Create admin'})).toBeNull()
 expect(screen.queryByRole('heading',{name:'Backup & restore'})).toBeNull()
 expect(request).not.toHaveBeenCalledWith('/api/admin/backups',expect.anything())
 expect(request).not.toHaveBeenCalledWith('/api/admin/audit',expect.anything())
 fireEvent.click(screen.getByRole('button',{name:'Manage Alice workspace'}))
 expect(screen.getByRole('region',{name:'Workspace details'}).textContent).toContain('Alice workspace')
 expect(screen.getAllByRole('checkbox',{name:/Job links access for/})).toHaveLength(1)
 fireEvent.click(screen.getByRole('tab',{name:'Backups'}))
 expect(await screen.findByRole('heading',{name:'Backup & restore'})).toBeTruthy()
 expect(screen.queryByRole('region',{name:'Workspace details'})).toBeNull()
 fireEvent.click(screen.getByRole('tab',{name:'Activity'}))
 await waitFor(()=>expect(request).toHaveBeenCalledWith('/api/admin/audit',expect.anything()))
})
it('searches workspaces and clears a password form when selection changes',async()=>{
 mount();fireEvent.click(await screen.findByRole('button',{name:'Manage Alice workspace'}))
 fireEvent.click(screen.getByRole('button',{name:'Reset password'}))
 fireEvent.change(screen.getByLabelText('New temporary password for alice'),{target:{value:'temporary-pass-123'}})
 fireEvent.click(screen.getByRole('button',{name:'Manage Original workspace'}))
 expect(screen.queryByLabelText('New temporary password for alice')).toBeNull()
 fireEvent.change(screen.getByLabelText('Search workspaces'),{target:{value:'alice'}})
 expect(screen.queryByRole('button',{name:'Manage Original workspace'})).toBeNull()
 expect(screen.getByRole('region',{name:'Workspace details'}).textContent).toContain('Alice workspace')
 fireEvent.click(screen.getByRole('button',{name:'Reset password'}))
 expect(screen.getByLabelText('New temporary password for alice')).toHaveProperty('value','')
})
it('preserves an admin creation draft when changing tasks and clears it on Cancel',async()=>{
 mount();await screen.findByRole('button',{name:'Manage Alice workspace'})
 fireEvent.click(screen.getByRole('button',{name:'Add admin'}))
 fireEvent.change(screen.getByLabelText('Username'),{target:{value:'bob'}})
 fireEvent.click(screen.getByRole('tab',{name:'Workspaces'}))
 expect(screen.queryByLabelText('Username')).toBeNull()
 fireEvent.click(screen.getByRole('button',{name:'Add admin'}))
 expect(screen.getByLabelText('Username')).toHaveProperty('value','bob')
 fireEvent.click(screen.getByRole('button',{name:'Cancel'}))
 fireEvent.click(screen.getByRole('button',{name:'Add admin'}))
 expect(screen.getByLabelText('Username')).toHaveProperty('value','')
})
it('keeps workspace controls and a password draft through a failed status refresh',async()=>{
 mount();fireEvent.click(await screen.findByRole('button',{name:'Manage Alice workspace'}))
 fireEvent.click(screen.getByRole('button',{name:'Reset password'}))
 fireEvent.change(screen.getByLabelText('New temporary password for alice'),{target:{value:'temporary-pass-123'}})
 vi.mocked(request).mockRejectedValueOnce(new Error('Status unavailable'))
 await clients[0].refetchQueries({queryKey:['owner-admins']})
 await screen.findByText(/Workspace status could not refresh/)
 expect(screen.getByLabelText('New temporary password for alice')).toHaveProperty('value','temporary-pass-123')
})
it.each([false,true])('lets the owner change Job links access from %s',async(granted)=>{
 vi.mocked(api.post).mockResolvedValue({ok:true})
 mount(granted)
 await screen.findByRole('button',{name:'Manage Alice workspace'})
 expect(screen.getByText('Job links access: always enabled')).toBeTruthy()
 fireEvent.click(screen.getByRole('button',{name:'Manage Alice workspace'}))
 const toggle=await screen.findByRole('checkbox',{name:'Job links access for alice'}) as HTMLInputElement
 expect(toggle.checked).toBe(granted)
 expect(screen.queryByRole('checkbox',{name:'Job links access for owner'})).toBeNull()
 fireEvent.click(toggle)
 await waitFor(()=>expect(api.post).toHaveBeenCalledWith('/api/admin/users/2',{job_links_access:!granted}))
})
it("creates an admin with workspace and temporary password",async()=>{
  vi.mocked(api.post).mockResolvedValue({ok:true})
  mount();await screen.findByRole("button",{name:"Manage Alice workspace"})
  fireEvent.click(screen.getByRole("button",{name:"Add admin"}))
  fireEvent.change(screen.getByLabelText("Username"),{target:{value:"bob"}})
  fireEvent.change(screen.getByLabelText("Workspace name"),{target:{value:"Bob workspace"}})
  fireEvent.change(screen.getByLabelText("Temporary password"),{target:{value:"temporary-pass-123"}})
  fireEvent.click(screen.getByRole("button",{name:"Create admin"}))
  await waitFor(()=>expect(api.post).toHaveBeenCalledWith("/api/admin/users",{username:"bob",workspace_name:"Bob workspace",password:"temporary-pass-123"}))
})
it("suspends access without deleting the workspace",async()=>{
  vi.spyOn(window,"confirm").mockReturnValue(true)
  vi.mocked(api.post).mockResolvedValue({ok:true})
  mount();fireEvent.click(await screen.findByRole("button",{name:"Manage Alice workspace"}));fireEvent.click(screen.getByRole("button",{name:"Suspend"}))
  await waitFor(()=>expect(api.post).toHaveBeenCalledWith("/api/admin/users/2",{enabled:false}))
  expect(screen.queryByRole("button",{name:"Delete"})).toBeNull()
})
it("does not offer owner controls or load other workspaces to an added admin",async()=>{
  state.owner=false;mount()
  expect(screen.getByRole("heading",{name:"Owner access required"})).toBeTruthy()
  expect(request).not.toHaveBeenCalled()
  expect(screen.queryByRole("button",{name:"Create admin"})).toBeNull()
})

it("shows browser presence separately from workspace server health",async()=>{
  mount()
  await screen.findByText("Alice workspace")
  expect(screen.getByText("Online")).toBeTruthy()
  expect(screen.getByText("Offline")).toBeTruthy()
})

it("removes only a non-owner workspace after explicit confirmation",async()=>{
  const confirm=vi.spyOn(window,"confirm").mockReturnValue(false)
  vi.mocked(api.post).mockResolvedValue({ok:true})
  mount();fireEvent.click(await screen.findByRole("button",{name:"Manage Alice workspace"}));const button=screen.getByRole("button",{name:"Remove Alice workspace"})
  expect(screen.queryByRole("button",{name:"Remove Original workspace"})).toBeNull()
  fireEvent.click(button)
  expect(api.post).not.toHaveBeenCalled()
  confirm.mockReturnValue(true);fireEvent.click(button)
  await waitFor(()=>expect(api.post).toHaveBeenCalledWith("/api/admin/users/2/remove",{username:"alice"}))
  expect(confirm.mock.calls.at(-1)?.[0]).toContain("retained")
})
