 await waitFor(()=>{
  const url=new URL(String(fetch.mock.lastCall?.[0]),'http://localhost')
  expect(url.searchParams.get('only_one_page')).toBe('true')
  expect(url.searchParams.get('exclude_one_page')).toBe('false')
 })
